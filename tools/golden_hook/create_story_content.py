records=[]
compiled={}
for group, lines in groups.items():
    compiled[group]=[]
    for i,(speaker,text,mood) in enumerate(lines,1):
        record={'id':f'{group}_{i:02d}','speaker':speaker,'text':text,'mood':mood}
        compiled[group].append(record)
        records.append({'group':group,**record,'audio':f'assets/golden_hook/audio/voice/{record["id"]}.wav','status':'Windows SAPI provisional / replaceable'})
(ROOT/'game/golden_hook/dialogue_data.gd').write_text('extends RefCounted\n## Original chapter dialogue. Replace WAV files by these stable line IDs.\nconst GROUPS='+json.dumps(compiled,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
with (ROOT/'docs/golden_hook/DIALOGUE_AND_VOICE.csv').open('w',encoding='utf-8-sig',newline='') as f:
    writer=csv.DictWriter(f,fieldnames=records[0].keys()); writer.writeheader(); writer.writerows(records)
(Path(__file__).parent/'voice_records.json').write_text(json.dumps(records,ensure_ascii=False),encoding='utf-8')
